// Renders the model tables of the docs from web/models/ (the registry) between <!-- models:start --> and
// <!-- models:end --> in README.md and docs/hardware.md. Also checks the hand-written docs: every repo-relative link
// and anchor and every path in backticks must exist, every `just <recipe>` must be a recipe of the justfile, and
// docs/README.md (the hand-written index) must link every Markdown file.
//
//   bun docs/tools/gen-docs.ts           write the generated blocks
//   bun docs/tools/gen-docs.ts --check   fail when a block is out of date or a link/recipe is broken
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { loadModels } from '../../web/models/index';
import { ALL_OUTPUTS, DOC_FILES, REGISTRY_JSON } from '../../scripts/generated';
import { FORUM_TESTERS, MAINTAINERS, TESTERS } from './testers';
import { format } from '../../scripts/format';
import { CAPABILITIES, type Capability, type Model, type Overall, SERIES, monthYear, overallStatus } from '../../web/models/schema';
import { CAPABILITY_LABEL, EVIDENCE_HELP, EVIDENCE_LABEL, OVERALL_HELP, OVERALL_LABEL, checkText } from '../site/content';

const root = resolve(import.meta.dir, '../..');
const SITE = 'https://ugreen-nas-control.github.io/ugreen-nas-control';
const NOTE = '<!-- Generated by docs/tools/gen-docs.ts from web/models/. Do not edit; run `just docs`. -->';
const note = (source: string) => NOTE.replace('web/models/', source);

const models = await loadModels();

const lower = (t: string) => t.replace(/\.$/, '').replace(/^./, c => c.toLowerCase());
const link = (m: Model) => `[${m.name}](${SITE}/models/${m.id}/)`;

function table(header: string[], rows: string[][]): string {
    return [`| ${header.join(' | ')} |`, `| ${header.map(() => '---').join(' | ')} |`, ...rows.map(r => `| ${r.join(' | ')} |`)].join('\n');
}

function cellText(m: Model, cap: Capability): string {
    const c = m.verified[cap];
    if (c.status === 'unsupported') return 'not offered';
    const when = [c.version ?? '', monthYear(c.date)].filter(Boolean).join(', ');
    return when ? `${EVIDENCE_LABEL[c.status]} (${when})` : EVIDENCE_LABEL[c.status];
}

function summary(): string {
    const rows = models.map(m => [link(m), ...CAPABILITIES.map(c => cellText(m, c)), OVERALL_LABEL[overallStatus(m)]]);
    const words = (Object.keys(EVIDENCE_LABEL) as (keyof typeof EVIDENCE_LABEL)[]).map(e => `**${EVIDENCE_LABEL[e]}**: ${lower(EVIDENCE_HELP[e])}`).join('. ');
    return [table(['Model', ...CAPABILITIES.map(c => CAPABILITY_LABEL[c]), 'Overall'], rows), '', `${words}.`].join('\n');
}

const OVERALL_SYMBOL: Record<Overall, string> = { verified: '●', community: '◔', partial: '◐', expected: '○' };
const RANK: Record<Overall, number> = { verified: 0, partial: 1, community: 2, expected: 3 };

/** README list: one line per series, models grouped by overall status (best first); the full matrix stays in docs/hardware.md. */
function compact(): string {
    const overalls = (Object.keys(RANK) as Overall[]).filter(o => models.some(m => overallStatus(m) === o));
    const counts = overalls.map(o => `${models.filter(m => overallStatus(m) === o).length} ${OVERALL_LABEL[o].toLowerCase()}`).join(', ');
    const legend = overalls.map(o => `${OVERALL_SYMBOL[o]} ${OVERALL_LABEL[o].toLowerCase()}`).join(' · ');
    const lines = SERIES.map(s => {
        const ms = models
            .filter(m => m.series === s)
            .sort((x, y) => RANK[overallStatus(x)] - RANK[overallStatus(y)] || x.name.localeCompare(y.name, 'en', { numeric: true }));
        const parts = overalls
            .map(o => ({ o, g: ms.filter(m => overallStatus(m) === o) }))
            .filter(x => x.g.length)
            .map(x => `${OVERALL_SYMBOL[x.o]} ${x.g.map(m => link(m)).join(', ')}`);
        return parts.length ? `- **${s}**: ${parts.join(' · ')}` : '';
    }).filter(Boolean);
    return [
        `**${counts}.** ${legend}.`,
        '',
        ...lines,
        '',
        'Per-capability status, versions, dates and evidence: [docs/hardware.md](docs/hardware.md), or the model page on the website.'
    ].join('\n');
}

const lan = (m: Model) => (m.lan ? m.lan.maxMbit.map(v => (v === null ? '?' : v >= 1000 ? `${v / 1000}G` : `${v}M`)).join(' ') : 'unknown');
const count = (n: number | null, zero = '0') => (n === null ? 'unknown' : n === 0 ? zero : String(n));

function detail(): string {
    const rows = models.map(m => [
        `\`${m.id}\``,
        m.name,
        m.cpu ?? 'unknown',
        count(m.bays, '0 (M.2 only)'),
        count(m.m2Slots),
        lan(m),
        m.fan
            ? `${m.fan.chip} (${Object.entries(m.fan.fans)
                  .map(([id, role]) => `${id}: ${role}`)
                  .join(', ')})`
            : 'none',
        m.caseVariant === 'none' ? 'none' : `\`${m.caseVariant}\``,
        `\`${m.dmiPattern}\``
    ]);
    const notes = models.map(m => `- **${m.name}**: ${m.note}`).join('\n');
    const evidence = models.flatMap(m =>
        CAPABILITIES.filter(c => m.verified[c].status !== 'unsupported').map(c => {
            const k = m.verified[c];
            const ref = k.ref ? `[link](${k.ref})` : '';
            return [m.name, CAPABILITY_LABEL[c], checkText(k), k.by ?? '', [k.note ?? '', ref].filter(Boolean).join(' ')];
        })
    );
    return [
        table(['Id', 'Model', 'CPU', 'Bays', 'M.2 slots', 'LAN', 'Fan controller (fan: role)', 'Case drawing', 'DMI product name'], rows),
        '',
        notes,
        '',
        '### Evidence per capability',
        '',
        table(['Model', 'Capability', 'State', 'Checked by', 'Note and evidence'], evidence),
        '',
        `Overall state: ${(Object.keys(OVERALL_LABEL) as (keyof typeof OVERALL_LABEL)[]).map(o => `**${OVERALL_LABEL[o]}**: ${lower(OVERALL_HELP[o])}`).join('. ')}.`
    ].join('\n');
}

function demoLinks(): string {
    return models.map(m => `- [${m.name}](${SITE}/demo/?model=${m.id})`).join('\n');
}

/** The registry as the backend's `ugreen-nas-ctl diag` reads it (go:embed): what each model is and how well each capability is known. */
function registryJson(): string {
    const out = models.map(m => ({
        id: m.id,
        name: m.name,
        series: m.series,
        dmiPattern: m.dmiPattern,
        fixtureDmi: m.fixtureDmi,
        cpu: m.cpu,
        bays: m.bays,
        m2Slots: m.m2Slots,
        m2: m.m2,
        lan: m.lan,
        led: m.led,
        caseView: m.caseView,
        fan: m.fan,
        overall: overallStatus(m),
        verified: m.verified,
        note: m.note
    }));
    return JSON.stringify({ schema: 1, models: out });
}

const RENDER: Record<Exclude<(typeof DOC_FILES)[number], typeof REGISTRY_JSON>, () => string> = {
    'README.md': compact,
    'docs/hardware.md': () => [summary(), '', '### Details per model', '', detail(), '', '### Live demo', '', demoLinks()].join('\n')
};

/** Round avatar linked to the GitHub profile. GitHub strips CSS, so the circle comes from wsrv.nl (no title: no hover tooltip). */
function avatar(login: string, size: number): string {
    const src = `https://wsrv.nl/?url=github.com/${login}.png&w=${size * 2}&h=${size * 2}&fit=cover&mask=circle`;
    return `<a href="https://github.com/${login}"><img src="${src}" width="${size}" height="${size}" alt="${login}"></a>`;
}

function testers(): string {
    const [a, b] = MAINTAINERS.map(m => `${avatar(m.login, 24)} [${m.name}](https://github.com/${m.login})`);
    const grid = TESTERS.map(t => avatar(t.login, 48)).join('\n');
    const named = TESTERS.map(t => `[${t.login}](https://github.com/${t.login}) (${t.did})`);
    const last = named.length - 1;
    const list = last > 0 ? `${named.slice(0, last).join(', ')} and ${named[last]}` : named.join('');
    return `Maintained by ${a} and ${b}.\n\n${grid}\n\nThanks to ${list} for testing and translating. And on the Unraid forum: ${FORUM_TESTERS.join(', ')}.`;
}

function splice(text: string, body: string, name = 'models', source = 'web/models/'): string {
    const start = `<!-- ${name}:start -->`;
    const end = `<!-- ${name}:end -->`;
    const a = text.indexOf(start);
    const b = text.indexOf(end);
    if (a < 0 || b < a) throw new Error(`markers ${start} / ${end} missing`);
    return `${text.slice(0, a + start.length)}\n${note(source)}\n\n${body}\n\n${text.slice(b)}`;
}

function markdownFiles(): string[] {
    const docs = readdirSync(join(root, 'docs'))
        .filter(f => f.endsWith('.md'))
        .map(f => `docs/${f}`);
    return ['README.md', '.github/CONTRIBUTING.md', '.github/SECURITY.md', '.github/CODE_OF_CONDUCT.md', ...docs].filter(f => existsSync(join(root, f)));
}

/** Build output declared in scripts/generated.ts (a file, a folder ending in /, or a folder that holds one) is not in a clean checkout. */
function isGeneratedOutput(path: string): boolean {
    const p = path.replace(/\/$/, '');
    return ALL_OUTPUTS.some(o => (o.endsWith('/') ? p === o.slice(0, -1) || p.startsWith(o) : p === o || o.startsWith(`${p}/`)));
}

const g1 = (m: RegExpMatchArray): string => m[1] ?? '';

function recipes(): Set<string> {
    const names = readFileSync(join(root, 'justfile'), 'utf8').matchAll(/^([a-z][a-z0-9_-]*)(?:\s+[^:\n]*)?:(?!=)/gm);
    return new Set([...names].map(m => g1(m)));
}

/** GitHub's anchor for a heading: lower case, markdown and punctuation dropped, spaces to hyphens, repeats numbered. */
function anchors(text: string): Set<string> {
    const seen = new Map<string, number>();
    const out = new Set<string>();
    for (const m of text.replace(/```[\s\S]*?```/g, '').matchAll(/^#{1,6} +(.+?) *#*$/gm)) {
        const plain = g1(m)
            .replace(/\[([^\]]*)\]\([^)]*\)/g, '$1')
            .replace(/[`*_]/g, '');
        const slug = plain
            .toLowerCase()
            .replace(/[^\p{L}\p{N}\s-]/gu, '')
            .trim()
            .replace(/\s/g, '-');
        const n = seen.get(slug) ?? 0;
        seen.set(slug, n + 1);
        out.add(n ? `${slug}-${n}` : slug);
    }
    return out;
}

function problems(file: string, text: string, known: Set<string>): string[] {
    const bad: string[] = [];
    const base = dirname(join(root, file));
    const body = text.replace(/```[\s\S]*?```/g, m => m.replace(/\[[^\]]*\]\([^)]*\)/g, '')); // links inside fences are examples
    for (const m of body.matchAll(/\]\(([^)\s]+)\)/g)) {
        const [target = '', frag] = g1(m).split('#');
        if (/^(https?:|mailto:)/.test(target)) continue;
        const dest = target ? resolve(base, target) : join(root, file);
        if (target && !existsSync(dest)) {
            bad.push(`${file}: broken link ${g1(m)}`);
            continue;
        }
        if (frag && dest.endsWith('.md') && !anchors(readFileSync(dest, 'utf8')).has(frag)) bad.push(`${file}: broken anchor ${g1(m)}`);
    }
    for (const m of body.matchAll(/(?:src|href)="([^"]+)"/g)) {
        if (/^(https?:|#)/.test(g1(m))) continue;
        if (!existsSync(resolve(base, g1(m)))) bad.push(`${file}: broken path ${g1(m)}`);
    }
    for (const m of body.matchAll(/`((?:backend|web|scripts|plugin|plugins|docs|\.github|\.changes|\.build)\/[A-Za-z0-9_./-]+)`/g)) {
        if (/[*<>]/.test(g1(m))) continue;
        if (isGeneratedOutput(g1(m))) continue;
        if (!existsSync(resolve(root, g1(m).replace(/\/$/, '')))) bad.push(`${file}: missing path ${g1(m)}`);
    }
    for (const m of body.matchAll(/`just ([a-z][a-z0-9_-]*)/g)) {
        if (!known.has(g1(m))) bad.push(`${file}: no just recipe "${g1(m)}"`);
    }
    return bad;
}

const check = process.argv.includes('--check');
const errors: string[] = [];

{
    const path = join(root, REGISTRY_JSON);
    const next = format(REGISTRY_JSON, registryJson());
    const current = existsSync(path) ? readFileSync(path, 'utf8') : '';
    if (next !== current) {
        if (check) errors.push(`${REGISTRY_JSON}: out of date (run just docs)`);
        else {
            writeFileSync(path, next);
            console.log(`wrote ${REGISTRY_JSON}`);
        }
    }
}

for (const [file, render] of Object.entries(RENDER)) {
    const path = join(root, file);
    const current = readFileSync(path, 'utf8');
    const next = format(
        file,
        file === 'README.md' ? splice(splice(current, render()), testers(), 'testers', 'docs/tools/testers.ts') : splice(current, render())
    );
    if (next === current) continue;
    if (check) errors.push(`${file}: generated block is out of date (run just docs)`);
    else {
        writeFileSync(path, next);
        console.log(`wrote ${file}`);
    }
}

{
    const index = readFileSync(join(root, 'docs/README.md'), 'utf8');
    for (const f of markdownFiles()) {
        if (f === 'docs/README.md') continue;
        if (!index.includes(`](${relative(join(root, 'docs'), join(root, f))})`)) errors.push(`docs/README.md: no link to ${f}`);
    }
}

// README: model names and statuses come only from the generated blocks, so adding or verifying a model never needs a hand edit.
{
    const readme = readFileSync(join(root, 'README.md'), 'utf8').replace(/<!-- (\w+):start -->[\s\S]*?<!-- \1:end -->/g, '');
    const names = models.map(m => m.name).sort((a, b) => b.length - a.length);
    for (const n of names)
        if (readme.includes(n)) errors.push(`README.md: model name "${n}" outside the generated blocks (the list is generated; link docs/hardware.md instead)`);
    const family = readme.match(/\b(?:i?DXP?|DH)\d{3,4}\w*/g);
    if (family) errors.push(`README.md: model name ${[...new Set(family)].join(', ')} outside the generated blocks`);
}

const known = recipes();
for (const file of markdownFiles()) errors.push(...problems(file, readFileSync(join(root, file), 'utf8'), known));

if (errors.length) {
    for (const e of errors) console.error(e);
    process.exit(1);
}
if (check) console.log(`docs ok: ${models.length} models, ${markdownFiles().length} files`);
