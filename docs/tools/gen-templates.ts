// Writes the two issue forms the plugin's Feedback page pre-fills (.github/ISSUE_TEMPLATE/model-report.yml and bug.yml).
// The capability fields come from the model registry (web/models/schema.ts CAPABILITIES) and the field ids from
// web/src/features/nas/feedback.ts, which builds the link: a field id exists in one place only.
//
//   bun docs/tools/gen-templates.ts           write the forms
//   bun docs/tools/gen-templates.ts --check   fail when a form is out of date
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { TEMPLATE_FILES } from '../../scripts/generated';
import { format } from '../../scripts/format';
import { CAPABILITIES, CAPABILITY_LABEL } from '../../web/models/schema';
import { FIELD } from '../../web/src/features/nas/feedback';

const root = resolve(import.meta.dir, '../..');
const DIAG_DOC = 'https://github.com/ugreen-nas-control/ugreen-nas-control/blob/next/docs/cli.md#diagnostics';
const BANNER = '# Generated by docs/tools/gen-templates.ts from the model registry and web/src/features/nas/feedback.ts. Do not edit; run `just docs`.';

const q = (text: string): string => JSON.stringify(text);

const versions = `  - type: input
    id: ${FIELD.versions}
    attributes:
      label: Unraid and plugin version
      placeholder: Unraid 7.1.4, plugin 5.3.1
    validations:
      required: true`;

const area = `  - type: dropdown
    id: area
    attributes:
      label: Area
      options:
        - Fans
        - LEDs
        - Front panel and power-on (buttons, beeper, power-on after power loss)
        - Dashboard widget
        - Plugin page
        - MQTT / Home Assistant
        - Install and update
        - Website
        - Other
    validations:
      required: true`;

const DIAG_PLACEHOLDER = 'Paste the copied device data here (Ctrl+V / Cmd+V)';
const BUG_DIAG_PLACEHOLDER = "Paste the copied device data, or write why it's not possible.";

const diag = (description: string, required: boolean, placeholder = DIAG_PLACEHOLDER): string => `  - type: textarea
    id: ${FIELD.diag}
    attributes:
      label: Device data (diag)
      description: ${q(description)}
      placeholder: ${q(placeholder)}${
          required
              ? `
    validations:
      required: true`
              : ''
      }`;

const DIAG_HOW = `In the plugin open Feedback, collect the data and use the button there: it copies the data and opens this form. Paste it here. By hand: run /usr/local/emhttp/plugins/ugreen-nas-control/backend/ugreen-nas-ctl diag as root on the Unraid box and paste the output. It is scrubbed (no serial numbers, IP or MAC addresses, host or drive names) and read only; what it collects: ${DIAG_DOC}`;

const results = (required: boolean): string => `  - type: textarea
    id: ${FIELD.results}
    attributes:
      label: What works on your device
      description: ${q(`One line per capability: ${CAPABILITIES.map(c => CAPABILITY_LABEL[c]).join(', ')}. Say works, does not work or not tried. The plugin's Feedback page fills this in.`)}${
          required
              ? `
    validations:
      required: true`
              : ''
      }`;

const summary = `  - type: textarea
    id: ${FIELD.summary}
    attributes:
      label: Check summary
      description: What the plugin found on your device.`;

const model = `  - type: input
    id: ${FIELD.model}
    attributes:
      label: NAS model
      description: The DMI product name (cat /sys/class/dmi/id/product_name)
      placeholder: DXP4800 Plus
    validations:
      required: true`;

const FILES: Record<(typeof TEMPLATE_FILES)[number], string> = {
    '.github/ISSUE_TEMPLATE/model-report.yml': `${BANNER}
name: Model report
description: Tell us what works on your UGREEN model.
labels: [model-report]
body:
${model}
${versions}
${results(true)}
${summary}
  - type: textarea
    id: ${FIELD.notes}
    attributes:
      label: What does not work, anything else
${diag(DIAG_HOW, true)}
  - type: markdown
    attributes:
      value: Remove serial numbers and IP addresses from anything else you paste.
`,
    '.github/ISSUE_TEMPLATE/bug.yml': `${BANNER}
name: Bug report
description: Something does not work as described.
labels: [bug]
body:
${model}
${versions}
${area}
  - type: textarea
    id: ${FIELD.what}
    attributes:
      label: What happened, and what did you expect
    validations:
      required: true
  - type: textarea
    id: steps
    attributes:
      label: Steps to reproduce
${results(false)}
${summary}
${diag(DIAG_HOW, true, BUG_DIAG_PLACEHOLDER)}
  - type: markdown
    attributes:
      value: Remove serial numbers and IP addresses from anything else you paste.
`
};

const check = process.argv.includes('--check');
const errors: string[] = [];
for (const [file, text] of Object.entries(FILES)) {
    const path = join(root, file);
    const next = format(file, text);
    const current = existsSync(path) ? readFileSync(path, 'utf8') : '';
    if (next === current) continue;
    if (check) errors.push(`${file}: out of date (run just docs)`);
    else {
        writeFileSync(path, next);
        console.log(`wrote ${file}`);
    }
}
if (errors.length) {
    console.error(errors.join('\n'));
    process.exit(1);
}
